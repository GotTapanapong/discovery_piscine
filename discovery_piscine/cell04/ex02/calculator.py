#!/usr/bin/python3
num = int(input("Give me the first number: "))
num2 = int(input("Give me the second number: "))
print("Thank you! :)")

print("%d + %d = %d"%(num, num2, num+num2))
print("%d - %d = %d"%(num, num2, num-num2))
print("%d / %d = %d"%(num, num2, num/num2))
print("%d * %d = %d"%(num, num2, num*num2))